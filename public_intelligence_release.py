PUBLIC_INTELLIGENCE_SITEMAP_BATCH_SIZE = 5_000
PUBLIC_COMPANY_MIN_OBSERVED_VALUE = 10_000
PUBLIC_HEALTHCARE_DOMINANCE_SHARE = 0.8
PUBLIC_AWARD_MIN_OBSERVED_VALUE = 1_000_000
PUBLIC_AWARD_MIN_ACTIONS = 2
